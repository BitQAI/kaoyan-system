"""101 政治理论：结构图与时间线（声明式渲染，media_config.CHARTS 挂载）。

两个通用渲染器：
  render_flow(ax, spec)     — 方框 + 箭头 + 注释（结构/关系图）
  render_timeline(ax, spec) — 竖向时间线（历史脉络）
spec 坐标均为 0~1 相对坐标。
"""
import matplotlib.patches as mpatches

PALETTE = {
    "blue": ("#eaf1ff", "#2457d6"), "green": ("#e8f6ef", "#11845b"),
    "orange": ("#fff4e5", "#b96a00"), "red": ("#fdeeee", "#b33a3a"),
    "grey": ("#f2f4f8", "#6b7280"), "purple": ("#f1ecff", "#6d4ec7"),
}


def _box(ax, b):
    fc, ec = PALETTE[b.get("color", "blue")]
    x, y, w, h = b["x"], b["y"], b["w"], b["h"]
    ax.add_patch(mpatches.FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.008",
                 fc=fc, ec=ec, lw=1.2))
    ax.text(x + w / 2, y + h / 2, b["text"], fontsize=b.get("size", 7.4),
            ha="center", va="center", color=ec, linespacing=1.5)


def _arrow(ax, a):
    kw = dict(arrowstyle="-|>", color=a.get("color", "#8a94a6"), lw=1.2)
    if a.get("dash"):
        kw["linestyle"] = "--"
    ax.annotate("", xy=(a["x2"], a["y2"]), xytext=(a["x1"], a["y1"]),
                arrowprops=kw)
    if a.get("label"):
        ax.text((a["x1"] + a["x2"]) / 2, (a["y1"] + a["y2"]) / 2 + 0.02,
                a["label"], fontsize=6.6, ha="center", color="#6b7280")


def render_flow(ax, spec):
    for b in spec.get("boxes", []):
        _box(ax, b)
    for a in spec.get("arrows", []):
        _arrow(ax, a)
    for t in spec.get("texts", []):
        ax.text(t["x"], t["y"], t["text"], fontsize=t.get("size", 6.8),
                ha=t.get("ha", "center"), color=t.get("color", "#6b7280"),
                linespacing=1.5)
    ax.set_axis_off()
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)


def render_timeline(ax, spec):
    items = spec["items"]
    n = len(items)
    top, bottom = 0.94, 0.06
    ax.plot([0.13, 0.13], [bottom, top], color="#c9d4e8", lw=1.8)
    step = (top - bottom) / max(n - 1, 1)
    for i, it in enumerate(items):
        y = top - i * step
        hot = it.get("hot", False)
        color = "#b33a3a" if hot else "#2457d6"
        ax.plot([0.13], [y], marker="o", ms=4.2, color=color)
        ax.text(0.11, y, it["year"], fontsize=7.6, ha="right", va="center",
                color=color, fontweight="bold")
        ax.text(0.17, y, it["text"], fontsize=7.0, va="center", color="#333b45")
    ax.set_axis_off()
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)


def _flow(**kw):
    return lambda ax, spec=kw: render_flow(ax, spec)


def _tl(items):
    return lambda ax, spec={"items": items}: render_timeline(ax, spec)


